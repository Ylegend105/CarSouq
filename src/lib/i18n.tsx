const DICTS: Record<Locale, Dict> = { en, ar, fr };

interface I18nValue {
  locale: Locale;
  dir: "ltr" | "rtl";
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    try {
      const fromUrl = new URLSearchParams(window.location.search).get("lang") as Locale | null;
      const saved = localStorage.getItem("carsouq.locale") as Locale | null;
      const next = fromUrl && DICTS[fromUrl] ? fromUrl : saved && DICTS[saved] ? saved : null;
      // Rehydrate locale after mount; storage/URL aren't available during SSR render.
      // eslint-disable-next-line react-hooks/set-state-in-effect
      if (next) setLocaleState(next);
    } catch {}
  }, []);

  useEffect(() => {
    const dir = DIR[locale];
    document.documentElement.lang = locale;
    document.documentElement.dir = dir;
    document.body.dir = dir;
    try {
      localStorage.setItem("carsouq.locale", locale);
    } catch {}
  }, [locale]);

  const setLocale = useCallback((l: Locale) => setLocaleState(l), []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let str = DICTS[locale][key] ?? DICTS.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        }
      }
      return str;
    },
    [locale],
  );

  const value = useMemo<I18nValue>(
    () => ({ locale, dir: DIR[locale], setLocale, t }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
